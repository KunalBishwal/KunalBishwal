#!/usr/bin/env python3
"""Generate Kunal's dark/light terminal-style GitHub profile banners.

The design borrows the terminal-banner concept from emmi-lili/emmi-lili while
using a fresh layout and profile-specific copy. Other SVG stats/charts are
generated by scripts/cards.py and scripts/radar.py.
"""
from __future__ import annotations

import argparse
from pathlib import Path

THEMES = {
    "dark": {
        "bg": "#0d1117", "panel": "#111827", "panel2": "#151d2e",
        "border": "#30363d", "text": "#dbe4f0", "muted": "#8b9bb4",
        "accent": "#a99bff", "blue": "#60a5fa", "green": "#6ee7b7",
        "grid": "#253149", "title": "#f5f7ff",
    },
    "light": {
        "bg": "#f7f8fc", "panel": "#ffffff", "panel2": "#eef2fb",
        "border": "#d7ddec", "text": "#273149", "muted": "#67728b",
        "accent": "#715be8", "blue": "#1875c9", "green": "#16865d",
        "grid": "#dce2ee", "title": "#171a2b",
    },
}
FONT = "ui-sans-serif,-apple-system,BlinkMacSystemFont,Segoe UI,Helvetica,Arial,sans-serif"


def text(x, y, value, size, color, weight=400, anchor="start", extra=""):
    return (
        f'<text x="{x}" y="{y}" font-family="{FONT}" font-size="{size}" '
        f'font-weight="{weight}" text-anchor="{anchor}" fill="{color}" {extra}>'
        f'{value}</text>'
    )


def render(theme):
    c = THEMES[theme]
    s = [
        '<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="360" '
        'viewBox="0 0 1200 360" role="img" aria-label="Kunal Bishwal developer profile banner">',
        f'<defs><linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop stop-color="{c["bg"]}"/><stop offset="1" stop-color="{c["panel2"]}"/></linearGradient>',
        f'<linearGradient id="glow"><stop stop-color="{c["accent"]}"/><stop offset="1" stop-color="{c["blue"]}"/></linearGradient>',
        f'<pattern id="grid" width="28" height="28" patternUnits="userSpaceOnUse"><path d="M28 0H0V28" fill="none" stroke="{c["grid"]}" stroke-width="1"/></pattern></defs>',
        '<rect width="1200" height="360" rx="18" fill="url(#bg)"/><rect width="1200" height="360" rx="18" fill="url(#grid)"/>',
        f'<rect x="22" y="20" width="1156" height="320" rx="14" fill="{c["panel"]}" stroke="{c["border"]}"/>',
        f'<path d="M22 63H1178" stroke="{c["border"]}"/>',
    ]
    for x, color in zip((43, 59, 75), ("#ff6b6b", "#f5c451", "#42d392")):
        s.append(f'<circle cx="{x}" cy="42" r="5" fill="{color}"/>')
    s += [
        text(94, 46, "profile.sh — KUNALBISHWAL", 12, c["muted"], 600),
        text(1150, 46, "LIVE / PROFILE", 10, c["accent"], 600, "end"),
        text(52, 91, "kunal@github", 12, c["green"], 600),
        text(146, 91, ":~$ whoami", 12, c["text"], 500),
        text(52, 137, "KUNAL BISHWAL", 33, c["title"], 750),
        text(52, 166, "Full-stack engineering  /  Applied AI", 16, c["accent"], 600),
        text(52, 196, "SRM Institute of Science and Technology  ·  Class of 2027", 12, c["muted"]),
    ]
    rows = [
        ("FOCUS", "Full-stack products + practical AI"),
        ("BUILD", "React · Next.js · TypeScript · Node.js"),
        ("APPLIED AI", "Python · Computer Vision · LLMs"),
        ("STACK", "PostgreSQL · Docker · AWS"),
    ]
    for i, (key, value) in enumerate(rows):
        y = 231 + i * 25
        s += [
            text(52, y, key, 10, c["blue"], 700, extra='letter-spacing="1.2"'),
            text(145, y, value, 12, c["text"]),
        ]
    s += [
        f'<rect x="397" y="250" width="7" height="14" rx="1" fill="{c["accent"]}"><animate attributeName="opacity" values="1;0;1" dur="1.15s" repeatCount="indefinite"/></rect>',
        f'<rect x="765" y="82" width="385" height="232" rx="10" fill="{c["panel2"]}" stroke="{c["border"]}"/>',
        text(787, 108, "// system map", 11, c["muted"], 600),
        text(1128, 108, "v1.0", 10, c["green"], 600, "end"),
    ]
    for x, y, width, color in [
        (788, 132, 160, c["accent"]), (788, 151, 224, c["blue"]),
        (788, 170, 118, c["green"]), (788, 189, 194, c["muted"]),
        (788, 208, 143, c["accent"]),
    ]:
        s.append(f'<rect x="{x}" y="{y}" width="{width}" height="5" rx="2.5" fill="{color}" opacity=".84"/>')
    points = [(820, 268), (895, 244), (970, 273), (1040, 231), (1100, 266), (1005, 297), (905, 292)]
    for a, b in [(0, 1), (1, 2), (2, 3), (3, 4), (2, 5), (5, 6), (6, 0), (1, 6), (3, 5)]:
        x1, y1 = points[a]
        x2, y2 = points[b]
        s.append(f'<path d="M{x1} {y1}L{x2} {y2}" stroke="url(#glow)" stroke-width="1.5" opacity=".65"/>')
    for i, (x, y) in enumerate(points):
        color = c["accent"] if i % 2 == 0 else c["blue"]
        s.append(
            f'<circle cx="{x}" cy="{y}" r="5" fill="{color}">'
            f'<animate attributeName="r" values="4;6;4" dur="{2.1 + i * .17}s" repeatCount="indefinite"/></circle>'
        )
    s += [
        text(52, 318, "BUILD  /  LEARN  /  SHIP", 10, c["muted"], 600, extra='letter-spacing="2"'),
        text(1147, 318, "GITHUB.COM/KUNALBISHWAL", 10, c["muted"], 600, "end"),
        "</svg>",
    ]
    return "".join(s)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=Path("assets"))
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    out = args.out if args.out.is_absolute() else root / args.out
    out.mkdir(parents=True, exist_ok=True)
    for theme in ("dark", "light"):
        (out / f"banner-{theme}.svg").write_text(render(theme), encoding="utf-8")
    print("Generated dark and light terminal-style banners.")


if __name__ == "__main__":
    main()
